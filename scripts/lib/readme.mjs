import { assetPath } from './assets.mjs';
import { altText } from './content.mjs';

export const README_NOTICE = '<!-- Generated by scripts/build-profile.mjs from content/profile.json. Edit that file and run npm run build; do not edit README.md by hand. -->';

const ATTR_ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
const attr = (value) => String(value).replace(/[&<>"]/g, (ch) => ATTR_ESCAPES[ch]);
// Markdown text: escape < and > so GitHub never reads copy as HTML.
const md = (value) => String(value).replace(/</g, '&lt;').replace(/>/g, '&gt;');
const chips = (list) => list.map((chip) => `\`${chip}\``).join(' ');
const link = ({ text, href }) => `[${md(text)}](${href})`;

/** One drawing, switching between the whiteprint and the blueprint with the viewer's GitHub theme (ADR-003). */
export function picture(content, name) {
  return [
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="${assetPath('dark', name)}">`,
    `  <img src="${assetPath('light', name)}" width="100%" alt="${attr(altText(content, name))}">`,
    '</picture>',
  ].join('\n');
}

function projectBlock(content, project) {
  const after = [md(project.note), project.links.map(link).join(' · ')].filter(Boolean).join(' ');
  return [picture(content, project.id), md(project.paragraph), after ? `${chips(project.chips)}<br>${after}` : chips(project.chips)].join('\n\n');
}

export function renderReadme(content) {
  const { headings } = content.readme;
  const { experience, certificates, contact } = content;
  const blocks = [
    README_NOTICE,
    picture(content, 'hero'),
    md(content.intro),
    picture(content, 'now'),
    `## ${headings.work}`,
    ...content.projects.map((project) => projectBlock(content, project)),
    `## ${headings.experience}`,
    picture(content, 'schedule'),
    experience.list.map((x) => `- **${md(x.role)}**, ${md(x.where)}. ${md(x.period)}.<br>${md(x.detail)}`).join('\n'),
    `## ${headings.stack}`,
    picture(content, 'stack'),
    `## ${headings.certificates}`,
    picture(content, 'certificates'),
    [
      '<details>',
      `<summary>${md(certificates.listSummary)}</summary>`,
      '',
      certificates.list.map((entry) => `- **${md(entry.issuer)}:** ${md(entry.items)}`).join('\n'),
      '',
      '</details>',
    ].join('\n'),
    `## ${headings.contact}`,
    picture(content, 'contact'),
    contact.cards.map((card) => `**${md(card.label)}** ${link({ text: card.linkText, href: card.href })}`).join(' · '),
  ];
  return `${blocks.join('\n\n')}\n`;
}
