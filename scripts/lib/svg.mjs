import { STYLESHEET } from './styles.mjs';
import { tokenCss } from './tokens.mjs';
import { TYPE } from './typography.mjs';

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
const UNESCAPES = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" };

/** Escapes text for SVG content and double-quoted attributes. */
export const esc = (value) => String(value).replace(/[&<>"]/g, (ch) => ESCAPES[ch]);

/** Rounds to one decimal, the precision of the mockup's computed geometry. */
export const r1 = (n) => Math.round(n * 10) / 10;

/** Formats an animation delay in seconds: 0.18 -> "0.18s". */
export const sec = (n) => `${Number(n.toFixed(2))}s`;

/** Characters used per font face, read from the drawing's <text> elements (first class = typography class). */
export function collectGlyphs(body) {
  const glyphs = new Map();
  for (const [, attrs, inner] of body.matchAll(/<text\b([^>]*)>([\s\S]*?)<\/text>/g)) {
    const cls = /\bclass="([^"]*)"/.exec(attrs)?.[1].trim().split(/\s+/)[0];
    const type = TYPE[cls];
    if (!type) throw new Error(`<text> needs a typography class as its first class; got "${cls ?? ''}" in <text${attrs}>`);
    const text = inner.replace(/<[^>]+>/g, '').replace(/&(amp|lt|gt|quot|#39);/g, (entity) => UNESCAPES[entity]);
    const set = glyphs.get(type.face) ?? new Set();
    for (const ch of text) set.add(ch);
    glyphs.set(type.face, set);
  }
  return new Map([...glyphs].map(([face, set]) => [face, [...set].sort().join('')]));
}

