/** One standalone SVG file for one theme. */
export function svgDocument({ width, height, title, body, theme, fontCss }) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="title">`,
    `<!-- ${GENERATED_NOTICE} -->`,
    `<title id="title">${esc(title)}</title>`,
    `<style>${fontCss}${tokenCss(theme)}`,
    STYLESHEET,
    '</style>',
    body,
    '</svg>',
    '',
  ].join('\n');
}
