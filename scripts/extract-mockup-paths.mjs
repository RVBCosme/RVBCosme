// One-off: copies long path data verbatim out of the approved mockup into scripts/components/paths.mjs.
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('../docs/superpowers/mockups/2026-09-23-profile-final.html', import.meta.url), 'utf8');
const grab = (pattern, what) => {
  const match = pattern.exec(html);
  if (!match) throw new Error(`Can't find the ${what} in the mockup`);
  return match[1];
};

const paths = {
  EAR_TRACE: grab(/<path class="wave" d="([^"]+)"/, 'eye aspect ratio trace'),
  REVISION_CLOUD: grab(/<path class="cloud" d="([^"]+)"/, 'revision cloud'),
  LINKEDIN_MARK: grab(/<path class="ico" transform="translate\(623\.2 129\.2\) scale\(\.9\)" d="([^"]+)"/, 'LinkedIn mark'),
  GITHUB_MARK: grab(/<path class="ico" transform="translate\(623\.2 197\.2\) scale\(1\.35\)" d="([^"]+)"/, 'GitHub mark'),
};

const header = [
  '// Generated by scripts/extract-mockup-paths.mjs: path data copied verbatim from the approved mockup,',
  '// docs/superpowers/mockups/2026-09-23-profile-final.html. Do not edit by hand.',
  '// LINKEDIN_MARK comes from Simple Icons (CC0 1.0); GITHUB_MARK is Octicons mark-github (MIT). See THIRD-PARTY-NOTICES.md.',
];
const body = Object.entries(paths).map(([name, d]) => `export const ${name} = ${JSON.stringify(d)};`);
writeFileSync(new URL('components/paths.mjs', import.meta.url), `${[...header, ...body].join('\n')}\n`);
for (const [name, d] of Object.entries(paths)) console.log(`${name}: ${d.length} characters`);
